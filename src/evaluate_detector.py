"""
FINAL evaluation of the frozen detector (detector.py) against the
holdout corpus and the stress corpus. Run this exactly ONCE, after all
dev-tuning (tune_on_dev.py) is finished - per LIMITATIONS.md, any change
to detector.py after looking at this output invalidates these numbers as
an honest held-out measurement; re-running after a change is "tuning on
the holdout/stress set" even if unintentional.

Reads only:
  - data/fixtures/corpus_holdout.jsonl  (never touched by tune_on_dev.py
    or generate_synthetic_data.py)
  - data/fixtures/stress_corpus.jsonl   (never touched by anything else)

Never reads planted_violations (see tests/test_detector.py).
"""
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import detector
import eval_metrics

FIXTURES_DIR = Path(__file__).resolve().parent.parent / "data" / "fixtures"
HOLDOUT_PATH = FIXTURES_DIR / "corpus_holdout.jsonl"
STRESS_PATH = FIXTURES_DIR / "stress_corpus.jsonl"
REPORT_PATH = Path(__file__).resolve().parent.parent / "EVALUATION.md"
REPORT_JSON_PATH = Path(__file__).resolve().parent.parent / "EVALUATION.json"


def load_jsonl(path):
    with path.open(encoding="utf-8") as f:
        return [json.loads(line) for line in f]


def detect_fn(text):
    return [category for category, _ in detector.detect_categories(text)]


def stress_scenario_breakdown_data(stress_entries):
    """Recall per (category, scenario) for stress true_violation entries -
    the out-of-template dimension corpus.py's holdout doesn't have.
    Returns a list of plain dicts (JSON-serializable)."""
    true_violations = [e for e in stress_entries if e["label"] == "true_violation"]
    scenarios = sorted({e["scenario"] for e in true_violations})
    rows = []
    for scenario in scenarios:
        subset = [e for e in true_violations if e["scenario"] == scenario]
        by_category = Counter()
        hit_by_category = Counter()
        for e in subset:
            by_category[e["category"]] += 1
            if e["category"] in detect_fn(e["text"]):
                hit_by_category[e["category"]] += 1
        for category in sorted(by_category):
            n = by_category[category]
            tp = hit_by_category[category]
            p, lo, hi = eval_metrics.wilson_ci(tp, n)
            rows.append({
                "scenario": scenario, "category": category, "n": n, "tp": tp,
                "recall": round(p, 4), "ci_low": round(lo, 4), "ci_high": round(hi, 4),
            })
    return rows


def stress_scenario_breakdown_text(rows):
    return "\n".join(
        f"  {r['scenario']:14s} {r['category']:10s} "
        f"recall={r['recall']:.0%} [{r['ci_low']:.0%},{r['ci_high']:.0%}] n={r['n']} (tp={r['tp']})"
        for r in rows
    )


def main():
    holdout = load_jsonl(HOLDOUT_PATH)
    stress = load_jsonl(STRESS_PATH)

    holdout_results = eval_metrics.evaluate(holdout, detect_fn)
    stress_results = eval_metrics.evaluate(stress, detect_fn)
    scenario_rows = stress_scenario_breakdown_data(stress)

    report = []
    report.append("# Phase 3 detector evaluation (one-time, final)\n")
    report.append("Generated by `src/evaluate_detector.py`. Per LIMITATIONS.md: this ran exactly\n"
                   "once against data never seen during tuning. Any subsequent change to\n"
                   "`detector.py` and re-run of this script invalidates these numbers as a\n"
                   "held-out measurement.\n")

    report.append("## Holdout corpus\n")
    report.append("```\n" + eval_metrics.format_report(holdout_results, "HOLDOUT") + "\n```\n")

    report.append("## Stress corpus (out-of-template)\n")
    report.append("```\n" + eval_metrics.format_report(stress_results, "STRESS") + "\n```\n")

    report.append("### Stress recall breakdown by scenario\n")
    report.append("```\n" + stress_scenario_breakdown_text(scenario_rows) + "\n```\n")

    text = "\n".join(report)
    print(text)
    REPORT_PATH.write_text(text, encoding="utf-8")
    print(f"\nWrote {REPORT_PATH}")

    json_payload = {
        "holdout": eval_metrics.results_to_json(holdout_results),
        "stress": eval_metrics.results_to_json(stress_results),
        "stress_scenario_breakdown": scenario_rows,
    }
    REPORT_JSON_PATH.write_text(json.dumps(json_payload, indent=2), encoding="utf-8")
    print(f"Wrote {REPORT_JSON_PATH}")


if __name__ == "__main__":
    sys.exit(main())
